"""Collect every results.jsonl in the repo into reports/comparisons/leaderboard.md.

    python -m gimpute.report

One table per (metric, mechanism); rows are methods, columns are dataset @ missing rate,
cells are mean +- std over seeds. Generated file: do not edit by hand.
"""
from __future__ import annotations

import statistics
from collections import defaultdict
from pathlib import Path

from .run import ROOT, read_rows

METRICS = [("test_acc", "Node classification accuracy (%)", 100.0, True), ("rmse", "Imputation RMSE on missing entries", 1.0, False)]


def collect() -> list:
    files = list((ROOT / "papers").glob("*/v*/results/results.jsonl")) + list((ROOT / "reports" / "baselines").glob("*.jsonl"))
    return [r for f in sorted(files) for r in read_rows(f)]


def fmt(values: list, scale: float) -> str:
    vals = [v * scale for v in values]
    mean = statistics.mean(vals)
    std = statistics.stdev(vals) if len(vals) > 1 else 0.0
    return f"{mean:.2f} ± {std:.2f} ({len(vals)})" if scale == 100.0 else f"{mean:.4f} ± {std:.4f} ({len(vals)})"


def main() -> None:
    rows = collect()
    lines = [
        "# Leaderboard",
        "",
        "Generated by `python -m gimpute.report` from every `results.jsonl` in the repository. Do not edit by hand.",
        "",
        "All methods share datasets, splits, masks and seeds (see `configs/protocol.yaml`). "
        "Cells are mean ± std over seeds, with the number of seeds in brackets. "
        "Accuracy uses the method's own classifier when it has one, otherwise the standard GCN on its imputed features.",
        "",
    ]
    if not rows:
        lines.append("No results yet.")
    for metric, title, scale, higher in METRICS:
        for mechanism in sorted({r["mechanism"] for r in rows}):
            sel = [r for r in rows if r["mechanism"] == mechanism and r.get(metric) is not None and r[metric] == r[metric]]
            if not sel:
                continue
            cols = sorted({(r["dataset"], r["rate"]) for r in sel})
            cell = defaultdict(list)
            for r in sel:
                cell[(f"{r['paper']} {r['version']}", r["dataset"], r["rate"])].append(r[metric])
            methods = sorted({k[0] for k in cell})
            lines += [f"## {title}: {mechanism} missingness ({'higher' if higher else 'lower'} is better)", ""]
            lines.append("| Method | " + " | ".join(f"{d} @ {rate:g}" for d, rate in cols) + " |")
            lines.append("|---|" + "---|" * len(cols))
            for m in methods:
                lines.append(f"| {m} | " + " | ".join(fmt(cell[(m, d, rate)], scale) if (m, d, rate) in cell else "-" for d, rate in cols) + " |")
            lines.append("")
    out = ROOT / "reports" / "comparisons" / "leaderboard.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)} from {len(rows)} result rows")


if __name__ == "__main__":
    main()
